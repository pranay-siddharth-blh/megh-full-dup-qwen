"""
The `app` schema in megh_db — everything this service owns (as opposed to the
read-only `curated`/`semantic` warehouse it queries): tenants, users, login
events, conversations + turns, and the query audit trail.

`ensure_schema()` runs at startup (idempotent CREATE TABLE IF NOT EXISTS) and
seeds the default tenant + imports config/users.yaml once if app.users is empty.
All access goes through backend.db's pooled `postgres` connection.
"""
import json
import logging
from pathlib import Path

import yaml

from app.database import db
from app.core import security
from app.core.config import settings

logger = logging.getLogger(__name__)

_ROOT = Path(__file__).resolve().parents[2]   # repo root

_DDL = """
-- Plain `CREATE SCHEMA IF NOT EXISTS app` requires CREATE privilege on the
-- *database*, even when the schema already exists (Postgres checks the
-- privilege before the existence check) — megh_app only has CREATE scoped
-- to the `app` schema itself (01_create_megh_app_role.sql), not the
-- database, so that form would crash every startup once the DB-role
-- cutover happens. This guarded form only runs CREATE SCHEMA (and so only
-- needs the privilege) when the schema is actually missing — the normal
-- case post-cutover is that 01_create_megh_app_role.sql already created it
-- as a superuser beforehand, so this becomes a true no-op requiring no
-- privilege at all. Found and fixed 2026-09-15 while verifying
-- multi-tenant-rls-scheme-scaleout's RLS migration against a disposable
-- Postgres connected as megh_app (not postgres) — a case this repo's
-- tests, which all connect as whatever DATABASE_URL points to without
-- actually exercising this line as a non-superuser, had never caught.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'app') THEN
        CREATE SCHEMA app;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS app.tenants (
    tenant_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        TEXT UNIQUE NOT NULL,
    name        TEXT NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS app.users (
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT NOT NULL REFERENCES app.tenants(tenant_id),
    username        TEXT UNIQUE NOT NULL,
    password_hash   TEXT NOT NULL,
    name            TEXT,
    role            TEXT NOT NULL,
    districts       TEXT[] NOT NULL DEFAULT '{}',
    blocks          TEXT[] NOT NULL DEFAULT '{}',
    schemes         TEXT[] NOT NULL DEFAULT '{}',
    granularity_cap TEXT,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_by      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login_at   TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_users_tenant ON app.users(tenant_id);

CREATE TABLE IF NOT EXISTS app.login_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT,
    user_id     BIGINT,
    username    TEXT,
    event       TEXT NOT NULL,                -- 'login_ok' | 'login_fail' | 'logout' | 'bootstrap'
    ok          BOOLEAN NOT NULL DEFAULT TRUE,
    ip          TEXT,
    user_agent  TEXT,
    detail      TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_login_events_time ON app.login_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_events_tenant ON app.login_events(tenant_id, created_at DESC);
-- "most recent auth event for this user" — powers the signed-in flag in list_users
CREATE INDEX IF NOT EXISTS idx_login_events_user ON app.login_events(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS app.conversations (
    conv_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL,
    user_id     BIGINT,
    session_id  TEXT UNIQUE NOT NULL,
    title       TEXT,
    started_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    turn_count  INTEGER NOT NULL DEFAULT 0,
    pinned      BOOLEAN NOT NULL DEFAULT FALSE,
    pinned_at   TIMESTAMPTZ,
    archived    BOOLEAN NOT NULL DEFAULT FALSE,
    archived_at TIMESTAMPTZ
);
-- Existing deployments: CREATE TABLE IF NOT EXISTS is a no-op once the table
-- is there, so the pin/archive columns are added separately. Idempotent.
ALTER TABLE app.conversations ADD COLUMN IF NOT EXISTS pinned      BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app.conversations ADD COLUMN IF NOT EXISTS pinned_at   TIMESTAMPTZ;
ALTER TABLE app.conversations ADD COLUMN IF NOT EXISTS archived    BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app.conversations ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ;
-- Conversation context layer (app/conversation/context_manager.py): the L2 durable copy of
-- the structured multi-turn state + rolling summary the in-process
-- session_store keeps as L1. Idempotent, additive — no existing row is touched
-- beyond getting NULL defaults for these three columns.
ALTER TABLE app.conversations ADD COLUMN IF NOT EXISTS summary             TEXT;
ALTER TABLE app.conversations ADD COLUMN IF NOT EXISTS context_state       JSONB;
ALTER TABLE app.conversations ADD COLUMN IF NOT EXISTS summary_updated_at  TIMESTAMPTZ;
-- The sidebar reads "my unarchived threads, pinned first, newest first".
CREATE INDEX IF NOT EXISTS idx_conv_user_shelf
    ON app.conversations(user_id, archived, pinned DESC, last_at DESC);
CREATE INDEX IF NOT EXISTS idx_conv_tenant_user ON app.conversations(tenant_id, user_id, last_at DESC);

CREATE TABLE IF NOT EXISTS app.conversation_turns (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conv_id             BIGINT NOT NULL REFERENCES app.conversations(conv_id),
    tenant_id           BIGINT NOT NULL,
    user_id             BIGINT,
    session_id          TEXT NOT NULL,
    question            TEXT NOT NULL,
    rewritten_question  TEXT,
    answer              TEXT,
    route               TEXT,
    intent              TEXT,
    schemes             TEXT[],
    resolved_entities   JSONB,
    sql                 TEXT,
    row_count           INTEGER,
    allowed             BOOLEAN,
    denied_by           TEXT,
    latency_ms          NUMERIC,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_turns_conv ON app.conversation_turns(conv_id, created_at);
CREATE INDEX IF NOT EXISTS idx_turns_tenant_time ON app.conversation_turns(tenant_id, created_at DESC);
-- The full answer payload (answer text + result rows + sql + follow-ups), so a
-- reopened chat can redraw its charts. Added separately — CREATE TABLE IF NOT
-- EXISTS is a no-op on existing deployments. Idempotent.
ALTER TABLE app.conversation_turns ADD COLUMN IF NOT EXISTS response JSONB;

CREATE TABLE IF NOT EXISTS app.query_audit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT,
    user_id      BIGINT,
    username     TEXT,
    session_id   TEXT,
    question     TEXT,
    rewritten_question TEXT,
    route        TEXT,
    granularity  TEXT,
    schemes      TEXT[],
    allowed      BOOLEAN,
    denied_by    TEXT,
    row_count    INTEGER,
    latency_ms   NUMERIC,
    ip           TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_audit_tenant_time ON app.query_audit(tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_user_time ON app.query_audit(user_id, created_at DESC);
-- Phase 2 audit-trail enrichment (openspec/changes/phase-2-audit-trail-enrichment):
-- the compliance trail was missing the executed SQL, a bounded result
-- preview, findings, and chart_type — all already computed by the pipeline
-- but never durably recorded. Added separately, same idempotent pattern as
-- the `response` column on conversation_turns above. No backfill of
-- historical rows; existing rows read NULL for these columns.
ALTER TABLE app.query_audit ADD COLUMN IF NOT EXISTS sql TEXT;
ALTER TABLE app.query_audit ADD COLUMN IF NOT EXISTS result_preview JSONB;
ALTER TABLE app.query_audit ADD COLUMN IF NOT EXISTS findings JSONB;
ALTER TABLE app.query_audit ADD COLUMN IF NOT EXISTS chart_type TEXT;
-- Added 2026-09-12, same change: GT proposal Sec 11.3's "final response"
-- was missed in the first pass (see tasks.md Group 5) -- already in
-- conversation_turns.answer, absent from the compliance trail until now.
ALTER TABLE app.query_audit ADD COLUMN IF NOT EXISTS answer TEXT;
-- openspec/changes/query-analyzer-consolidation: node 5.2's structured query
-- analysis and its node 5.1 scope-decision sibling (see
-- app/nlu/query_analyzer.py, app/orchestration/pipeline.py::_classify_scheme_detailed) were
-- computed on every DATA-route answer but never durably recorded -- this
-- was 11.3's own "no analyser output" gap. Same idempotent pattern as the
-- enrichment above; NULL on any route that doesn't compute them and on
-- existing rows.
ALTER TABLE app.query_audit ADD COLUMN IF NOT EXISTS analysis JSONB;
ALTER TABLE app.query_audit ADD COLUMN IF NOT EXISTS scope JSONB;
-- Step 9 (continuous improvement): the request's diagnostic trace — raw
-- question, QueryFrame before/after normalise, rules fired, assumptions,
-- clarification asked + slot, verifier results, repairs, fallback, latency per
-- stage (app/core/request_trace.py). Read by the admin "today's failures" view.
ALTER TABLE app.query_audit ADD COLUMN IF NOT EXISTS trace JSONB;

-- openspec/changes/multi-tenant-rls-scheme-scaleout: app.schemes is the
-- DB-backed source of truth scheme_registry.yaml syncs into
-- (app.knowledge.scheme_registry.sync_to_db()); app.tenant_schemes is the real
-- tenant<->scheme grant table that replaces auth.ROLE_PERMISSIONS'
-- hardcoded per-role scheme lists as the entitlement source once
-- TENANT_SCHEME_RLS_ENABLED is on (see app/core/auth.py::scope_from_user).
-- Both live in the `app` schema (megh_app already has CREATE here per
-- deploy/sql/01_create_megh_app_role.sql) so they follow this file's
-- existing idempotent runtime-DDL pattern, unlike the curated-schema RLS
-- work in deploy/sql/03_tenant_scheme_rls.sql, which needs a superuser.
CREATE TABLE IF NOT EXISTS app.schemes (
    scheme_id    TEXT PRIMARY KEY,
    display_name TEXT NOT NULL,
    is_shared    BOOLEAN NOT NULL DEFAULT FALSE,
    is_active    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS app.tenant_schemes (
    tenant_id   BIGINT NOT NULL REFERENCES app.tenants(tenant_id),
    scheme_id   TEXT NOT NULL REFERENCES app.schemes(scheme_id),
    granted_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    granted_by  BIGINT REFERENCES app.users(user_id),
    PRIMARY KEY (tenant_id, scheme_id)
);
CREATE INDEX IF NOT EXISTS idx_tenant_schemes_scheme ON app.tenant_schemes(scheme_id);
"""


async def ensure_schema() -> None:
    await db.execute_script(_DDL)
    logger.info("app schema ready")
    await _seed_default_tenant()
    await _seed_users_from_yaml()


async def _seed_default_tenant() -> int:
    row = await db.fetchrow("SELECT tenant_id FROM app.tenants WHERE code = $1",
                            [settings.DEFAULT_TENANT_CODE])
    if row:
        return row["tenant_id"]
    tid = await db.fetchval(
        "INSERT INTO app.tenants(code, name) VALUES ($1, $2) RETURNING tenant_id",
        [settings.DEFAULT_TENANT_CODE, settings.DEFAULT_TENANT_NAME],
    )
    logger.info("seeded default tenant %s (id=%s)", settings.DEFAULT_TENANT_CODE, tid)
    return tid


async def _seed_users_from_yaml() -> None:
    n = await db.fetchval("SELECT count(*) FROM app.users")
    if n and int(n) > 0:
        return
    path = _ROOT / settings.USERS_FILE
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        logger.warning("appdb: no %s to seed users from", path)
        return
    tid = await _seed_default_tenant()
    seeded = 0
    for rec in data.get("users", []):
        uid = str(rec.get("user_id", "")).strip()
        if not uid:
            continue
        # YAML seed users get username == user_id and a known dev password so the
        # first login works; the admin should rotate these immediately.
        username = rec.get("username", uid)
        pw = rec.get("password", "changeme123")
        role = rec.get("role", "analyst")
        try:
            await db.execute(
                """INSERT INTO app.users
                   (tenant_id, username, password_hash, name, role, districts, blocks,
                    schemes, granularity_cap, created_by)
                   VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9,'seed')
                   ON CONFLICT (username) DO NOTHING""",
                [tid, username, security.hash_password(pw), rec.get("name"), role,
                 _up(rec.get("districts")), _up(rec.get("blocks")),
                 list(rec.get("schemes") or []), rec.get("granularity_cap")],
            )
            seeded += 1
        except Exception as e:  # noqa: BLE001
            logger.warning("appdb: could not seed user %s: %s", username, e)
    logger.info("appdb: seeded %d users from %s (default password 'changeme123')", seeded, path.name)


def _up(values) -> list[str]:
    return [str(v).strip().upper() for v in (values or []) if str(v).strip()]


