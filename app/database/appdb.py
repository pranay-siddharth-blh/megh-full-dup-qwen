async def upsert_scheme(scheme_id: str, display_name: str, is_shared: bool) -> None:
    await db.execute(
        """INSERT INTO app.schemes (scheme_id, display_name, is_shared)
           VALUES ($1, $2, $3)
           ON CONFLICT (scheme_id) DO UPDATE
             SET display_name = EXCLUDED.display_name, is_shared = EXCLUDED.is_shared""",
        [scheme_id, display_name, is_shared],
    )


