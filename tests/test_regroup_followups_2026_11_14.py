# ── the frames check ─────────────────────────────────────────────────────────

def test_a_follow_up_that_names_its_grouping_is_not_a_lost_breakdown():
    base = {"id": 1, "q": "How many MGNREGA person-days were generated by district?", "route": "data",
            "schemes": ["MGNREGA"], "by": ["district"], "place": {}, "years": []}
    got = context_frames.check("How many MGNREGA person-days were generated by financial year?",
                               "now by financial year", base)
    assert got != "lost-breakdown"
    # a message that names no grouping still may not lose the one it continues
    assert context_frames.check("How many MGNREGA person-days were generated?", "and the total households?",
                                base) is not None


