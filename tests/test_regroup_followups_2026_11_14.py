"""Regroup follow-ups and measure-less all-scheme questions (2026-11-14).

The report: after any data answer, "break that down by district", "now break it down by block", "break it down by
financial year" and "break down as per scheme" were not answered. CTX-07 (KI-363) regroups only a statewide, ungrouped
answer and only by a place level; everything else went to the model rewrite, whose checks rejected the change of
grouping or lost the scheme and the measure. And "break ... down" (two words) was not a DATA cue.

  _BREAKDOWN_CUE           "break that down" is a cue like "breakdown"
  _c01_regroup_question    the previous question regrouped (c01), wired beside CTX-07 in c14
  context_frames.check     a follow-up that names its own grouping is not a "lost-breakdown"
  cross_scheme.detect      "the headline figure of every scheme" / "each scheme's figures" is a figure across the schemes

Offline: the unit functions, then a chain of regroups through the real graph with the model unreachable (the harness
of test_ctx07_followups_2026_10_29).
    .venv/Scripts/python.exe -m pytest tests/test_regroup_followups_2026_11_14.py -q
"""
