# ── through the graph ────────────────────────────────────────────────────────

@pytest.fixture
def chat(monkeypatch):
    for flag in ("CONTEXT_LAYER_ENABLED", "CONTEXT_STATE_ENABLED"):
        monkeypatch.setattr(settings, flag, True)
    seen, resolved = [], {}

    async def data(question, scope=None, **kw):
        seen.append(question)
        return {"route": "data", "intent": "DATA", "schemes": [resolved["scheme"]], "sql": "SELECT 1",
                "resolved_entities": dict(resolved["entities"]), "rows": [{"n": 1}], "data": [{"n": 1}],
                "row_count": 1, "answer": "answer."}
    stub_data_path(monkeypatch, data)

    async def no_model(*a, **k):
        raise RuntimeError("no model offline")
    monkeypatch.setattr(llm, "call_rewriter", no_model)
    s = Session(session_id=f"regroup-{time.time()}", user_id="u", created=time.time(), last_seen=time.time())

    def ask(q, scheme="MGNREGA", entities=None):
        resolved.update(scheme=scheme, entities=entities or {})
        n = len(seen)
        out = asyncio.run(graph_turn(q, session=s))
        s.turns.append(build_turn(q, out))
        return seen[-1] if len(seen) > n else None
    return ask


def test_a_chain_of_regroups_through_the_graph(chat):
    chat("How many MGNREGA person-days were generated in all of Meghalaya?")
    assert chat("break that down by district") == "How many MGNREGA person-days were generated by district"
    assert chat("now break it down by block") == "How many MGNREGA person-days were generated by block"
    assert chat("break it down by financial year") == "How many MGNREGA person-days were generated by financial year"
    assert chat("district wise") == "How many MGNREGA person-days were generated by district"


def test_a_regroup_inside_a_district_through_the_graph(chat):
    chat("MGNREGA expenditure in West Garo Hills", entities={"district": "WEST GARO HILLS"})
    assert chat("break that down by block", entities={"district": "WEST GARO HILLS"}) == \
        "MGNREGA expenditure in West Garo Hills by block"


def test_as_per_scheme_inside_cm_elevate_through_the_graph(chat):
    chat("How many CM Elevate applications are there?", scheme="CM Elevate")
    assert chat("break down as per scheme", scheme="CM Elevate") == "How many CM Elevate applications are there by scheme"


