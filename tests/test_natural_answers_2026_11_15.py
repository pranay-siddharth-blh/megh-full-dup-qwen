# ── A. the live voice's guard: honest roundings pass, invented figures do not ─
def test_speech_guard_accepts_a_marked_rounding_and_blocks_an_invention():
    facts = sg.facts_from("West Garo Hills has 35,039 Focus Plus beneficiaries; the total is ₹886.29 crore.")
    assert sg.deviations("about thirty-five thousand beneficiaries", facts) == []
    assert sg.deviations("nearly 890 crore", facts) == []
    assert sg.deviations("just over 35,000", facts) == []
    assert sg.deviations("34,000 beneficiaries", facts) == ["34000"]           # not marked, 3 % off
    assert sg.deviations("about 50,000 beneficiaries", facts) == ["50000"]     # invented, marked or not
    line, bad = sg.guard_line("West Garo Hills has about 50,000. The rest is on your screen.", facts)
    assert bad == ["50000"] and line.startswith(sg.ON_SCREEN_LINE)


