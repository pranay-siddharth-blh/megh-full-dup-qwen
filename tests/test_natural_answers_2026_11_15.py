def test_spoken_text_form_says_an_approximate_bracket_once_and_reads_a_list_intro():
    tot = "Total MGNREGA expenditure in Ri Bhoi for FY 2022-23 was ₹4,575.40 lakh (≈ ₹45.75 crore)."
    sp = p._c19_spoken_for_result(_result("q", "SELECT 1", [{"total_exp_lakh": 4575.40}], ["MGNREGA"], answer=tot))
    assert sp == "Total MGNREGA expenditure in Ri Bhoi for FY 2022-23 was about ₹46 crore."
    head = ("**All of Meghalaya, all financial years**\nEach scheme's headline figure (the figure its overview card "
            "leads with):\n- **MGNREGA**: 9,09,15,181 person-days (14,94,437 households given work)\n"
            "- **PMAY-G**: 1,71,107 houses sanctioned\n- **Focus Plus**: 3,85,671 disbursements\n"
            "Each scheme counts its own thing, so these figures are not added.")
    sp = p._c19_spoken_for_result(_result("q", "SELECT 1", [{"scheme": "MGNREGA", "v": 90915181},
                                                             {"scheme": "PMAY-G", "v": 171107}], ["MGNREGA"], answer=head))
    assert sp == ("Each scheme's headline figure: MGNREGA: just over 9 crore person-days; PMAY-G: just over 1.7 lakh "
                  "houses sanctioned. The full list is on your screen.")
    facts = sg.facts_from(head)
    assert all(sg.deviations(s, facts) == [] for s in sg.sentences(sp))
