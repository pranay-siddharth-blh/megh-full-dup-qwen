def _answer(q, sql, rows, schemes, ents):
    return run(p.compose_response(q, sql, rows, schemes=schemes, entities=ents))


def _lead(answer: str) -> str:
    return answer.split("\n")[0]


def _caps_places(text: str, rows: list) -> list:
    return [v for r in rows for k, v in r.items() if isinstance(v, str) and v.isupper() and len(v) > 3
            and p._c19_is_place_col(k) and v in text]


