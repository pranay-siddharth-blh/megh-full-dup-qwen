# ── A. the spoken form ───────────────────────────────────────────────────────
def _result(q, sql, rows, schemes, ents=None, answer=None):
    ans = answer if answer is not None else _answer(q, sql, rows, schemes, ents or {})
    return {"route": "data", "answer": ans, "data": rows, "rows": rows[:20], "sql": sql, "rewritten_question": q,
            "schemes": schemes, "resolved_entities": {}}


@pytest.mark.parametrize("kind,q,sql,rows,schemes,ents", CASES)
def test_spoken_form_is_short_conversational_and_every_number_honest(kind, q, sql, rows, schemes, ents):
    res = _result(q, sql, rows, schemes, ents)
    spoken = p._c19_spoken_for_result(res)
    assert spoken, res["answer"]
    assert len(spoken) <= 320
    assert spoken.count(".") <= 5 and "\n" not in spoken and "**" not in spoken
    assert not any(v in spoken for r in rows for k, v in r.items() if isinstance(v, str) and v.isupper()
                   and len(v) > 3 and p._c19_is_place_col(k))
    # every number is a row value, a figure computed from the rows, or an honest marked rounding of one
    shape = p._answer_shape(q, sql, rows)
    assert p._c19_spoken_numbers_ok(spoken, p._c19_allowed(shape, rows)), spoken
    # and the live voice's own guard lets every sentence through against the WRITTEN answer's figures
    facts = sg.facts_from(res["answer"])
    for s in sg.sentences(spoken):
        assert sg.deviations(s, facts) == [], (s, sg.deviations(s, facts))


