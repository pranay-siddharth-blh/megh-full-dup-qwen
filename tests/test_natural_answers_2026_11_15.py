@pytest.mark.parametrize("q", ["Take me back to the dashboard.", "go home", "close the chart"])
def test_the_chat_answers_a_navigation_command_without_the_pipeline(monkeypatch, q):
    async def drop(_sid):
        return None
    monkeypatch.setattr(cl, "_drop_paused_run", drop)
    layer = run(cl.prepare_turn(_session(), q))
    assert layer.action == "ui" and layer.changed
    r = layer.response
    assert r["route"] == "edge" and r["edge_type"] == "ui_command" and r["confidence"] == "low"
    assert "main screen" in r["answer"]
    assert "apply, book, pay" not in r["answer"] and "on your behalf" not in r["answer"]


