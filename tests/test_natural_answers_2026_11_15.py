@pytest.mark.parametrize("kind,q,sql,rows,schemes,ents", CASES)
def test_written_answer_is_natural_exact_and_in_title_case(natural_on, kind, q, sql, rows, schemes, ents):
    out = _answer(q, sql, rows, schemes, ents)
    shape = p._answer_shape(q, sql, rows)
    assert shape.kind == kind
    assert natural_on == [], "a natural answer needs no model call"
    lead = _lead(out)
    assert not any(r in out for r in ROBOTIC), out
    assert _caps_places(out, rows) == [], out                       # never "WEST GARO HILLS"
    assert lead[0].isupper() and lead.endswith(".")
    # every figure in the lead is a row value or a figure computed from the rows
    assert p._c19_spoken_numbers_ok(lead, p._c19_allowed(shape, rows)), lead
    # a figure is never beside another row's name
    assert p._c12_label_misbinds(out, p._c19_title_rows(rows)) == [], out
    # the list for the screen is still there, every value exact
    metric = shape.metric
    for r in rows:
        assert p._c12_fmt_value(metric, r[metric]).replace(",", "") in out.replace(",", "") or kind == "compare",             (r, out)


