def _fake_guard_model(monkeypatch, reply):
    async def fake_call_model(**kw):
        return reply
    monkeypatch.setattr(settings, "GUARDRAIL_MODEL_ENABLED", True)
    monkeypatch.setattr(llm, "call_model", fake_call_model)


@pytest.mark.parametrize("q", NAV_DESK + NAV_CHART + ["download the table as excel", "repeat that"])
@pytest.mark.parametrize("model_says", ['{"verdict": "OUT_OF_SCOPE", "category": "task"}',
                                        '{"verdict": "OUT_OF_SCOPE", "category": "general"}'])
def test_the_guardrail_never_refuses_a_screen_command_as_a_task(monkeypatch, q, model_says):
    _fake_guard_model(monkeypatch, model_says)
    assert guardrails.check_rules(q) is None and guardrails.check_scope_rules(q) is None
    assert run(guardrails.check_model(q)) is None


def test_a_real_task_is_still_refused(monkeypatch):
    _fake_guard_model(monkeypatch, '{"verdict": "OUT_OF_SCOPE", "category": "task"}')
    v = run(guardrails.check_model("please pay my pending wages to my account"))
    assert v is not None and v.category == "scope_task"
    _fake_guard_model(monkeypatch, '{"verdict": "UNSAFE", "category": "violence"}')
    v = run(guardrails.check_model("take me back to the dashboard"))
    assert v is not None and v.category == "violence"                     # a harm verdict is never overruled


