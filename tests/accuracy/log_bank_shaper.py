def mem_after(prev: list[str], options=None) -> "shaper.Memory":
    m = shaper.Memory()
    for i, p in enumerate(prev):
        m.asked(p, p)
        if options and i == len(prev) - 1:
            m.answered("Which one do you mean?", "clarification", list(options))
        else:
            m.answered("(answer)", "data", [])
    return m


def judge(out: str, must: list[str], lacks: list[str]) -> list[str]:
    low = (out or "").lower()
    probs = [f"lost {w!r}" for w in must if w.lower() not in low]
    probs += [f"carries {w!r}" for w in lacks if w.lower() in low]
    return probs


