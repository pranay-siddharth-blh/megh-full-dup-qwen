# ── the generated tables equal the hand-kept ones, for every scheme ──────────────

def test_queries_byte_identical():
    assert cf._QUERIES == OLD_QUERIES
    assert list(cf._QUERIES) == list(OLD_QUERIES)          # the same order too


@pytest.mark.parametrize("scheme", OLD_SUPPORTED)
def test_each_scheme_sql_strings_byte_identical(scheme):
    for new, old in zip(cf._QUERIES[scheme], OLD_QUERIES[scheme], strict=True):
        assert new[:3] == old[:3]
        for (m1, e1), (m2, e2) in zip(new[3], old[3], strict=True):
            assert (m1, e1.encode()) == (m2, e2.encode())


