@pytest.mark.parametrize("scheme", scheme_registry.NAMES)
def test_declaration_agrees_with_the_dataset_facts(scheme):
    e, facts = reg.BY_NAME[scheme], scheme_registry.DATASETS[scheme]
    assert e.has_money == (facts.money_unit is not None), "money: null <=> no money unit"
    assert e.years == facts.has_dates, "years <=> the dataset has a date column"
    assert e.village.count_view == scheme_registry.BY_NAME[scheme].main_view
    assert e.headline.view in {q.view for q in e.queries}
    # the count role is said in every answer; a scheme that counts applications is kept out of combined totals
    assert e.noun and e.count_note
    assert (e.noun == "applications") == (not e.in_combined)


def test_a_broken_declaration_fails_loudly(tmp_path):
    bad = tmp_path / "x.yaml"
    bad.write_text("schemes:\n  - name: MGNREGA\n    count: {noun: x}\n    money: null\n    village: "
                   "{count_view: v}\n    headline: {card: c, figure: f, label: l, noun: n, view: v, expr: e}\n"
                   "    queries:\n      - {view: v, district: d, block: b, metrics: {ben: 'COUNT(*); DROP'}}\n",
                   encoding="utf-8")
    with pytest.raises(reg.CrossRegistryError):
        reg.load(bad)
    missing = tmp_path / "y.yaml"
    missing.write_text("schemes: []\n", encoding="utf-8")
    with pytest.raises(reg.CrossRegistryError, match="no cross-scheme entry"):
        reg.load(missing)


def test_a_new_scheme_is_one_yaml_entry(tmp_path, monkeypatch):
    """Onboarding: an entry in the file is all the cross-scheme tables need."""
    import dataclasses
    text = reg.FILE.read_text(encoding="utf-8") + (
        "\n  - name: Newscheme\n    main: false\n    count: {noun: applications, note: applications, combined: false}\n"
        "    money: null\n    years: true\n    constituency: UPPER(ac_name)\n"
        "    village: {count_view: curated.v_new}\n"
        "    headline: {card: newscheme, figure: applications, label: Applications, noun: applications, "
        "view: curated.v_new, expr: COUNT(*)}\n"
        "    queries:\n      - view: curated.v_new\n        district: UPPER(lgd_district)\n"
        "        block: UPPER(lgd_block)\n        metrics: {ben: COUNT(*)}\n")
    f = tmp_path / "cross.yaml"
    f.write_text(text, encoding="utf-8")
    new = scheme_registry.Scheme("Newscheme", "newscheme", "Newscheme", "Newscheme", "curated.v_new", "New", True)
    monkeypatch.setattr(scheme_registry, "BY_NAME", {**scheme_registry.BY_NAME, "Newscheme": new})
    entries = reg.load(f)
    e = {x.name: x for x in entries}["Newscheme"]
    assert not e.has_money and not e.in_combined and e.headline.expr == "COUNT(*)"
    assert dataclasses.asdict(e)["queries"][0]["metrics"] == (("ben", "COUNT(*)"),)


